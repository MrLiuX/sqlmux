func yiRoundTrip(t *testing.T, c db.Conn, eng db.Engine, schema string, setup []string, clone string) {
	ctx := context.Background()
	for _, s := range setup {
		if _, err := c.Query(ctx, s); err != nil {
			t.Fatalf("%s: %v", s, err)
		}
	}
	cols, err := eng.TableColumns(ctx, c, schema, "t_rt")
	if err != nil {
		t.Fatal(err)
	}
	page, _, err := db.Page(ctx, c, eng, db.Query{Schema: schema, Table: "t_rt", Key: cols.Key(), Limit: 100})
	if err != nil {
		t.Fatal(err)
	}
	a := wide(160, 45)
	conn := a.sess.Conns[0]
	conn.eng = eng
	a.openTable(conn, db.Table{Schema: schema, Name: "t_rt"})
	tab := dataOf(a.focused())
	a.Update(pageMsg{tab: tab, seq: tab.seq, cols: cols, page: page})
	if _, err := c.Query(ctx, clone); err != nil {
		t.Fatal(err)
	}
	for i := range page.Rows {
		tab.row = i
		text, ok := clipText(keys(t, a, "yi"))
		if !ok {
			t.Errorf("row %d: nothing copied", i)
			continue
		}
		ins := strings.Replace(text, eng.Quote(schema, "t_rt"), eng.Quote(schema, "t_rt2"), 1)
		if _, err := c.Query(ctx, strings.TrimSuffix(ins, ";")); err != nil {
			t.Errorf("row %d: the INSERT fails: %v", i, err)
		}
	}
	back, _, err := db.Page(ctx, c, eng, db.Query{Schema: schema, Table: "t_rt2", Key: cols.Key(), Limit: 100})
	if err != nil {
		t.Fatal(err)
	}
	for i, row := range page.Rows {
		if i >= len(back.Rows) {
			t.Errorf("row %d not back", i)
			continue
		}
		for j, v := range row {
			w := back.Rows[i][j]
			if v != w {
				t.Errorf("row %d col %s (%s): shown %q null=%v -> back %q null=%v", i, page.Cols[j].Name, tab.column(page.Cols[j].Name).Type, v.S, v.Null, w.S, w.Null)
			}
		}
	}
}

