func TestYankInsertRoundTripMySQL(t *testing.T) {
	c, _, err := mysql.Connect(context.Background(), mysql.OwnDB(t), "", false)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	setup := []string{
		`drop table if exists t_rt, t_rt2`,
		`create table t_rt (
		 id int auto_increment primary key,
		 vc varchar(50), tx text, t1 tinyint(1), b1 bit(1), b8 bit(8), de decimal(10,3), fl float, dbl double,
		 j json, e enum('a','it''s'), s set('x','y'),
		 dt datetime(3), ts timestamp null, y year,
		 g int generated always as (t1 + 1) virtual, gs varchar(60) generated always as (concat(vc, '!')) stored,
		 df varchar(10) default 'dflt')`,
		`insert into t_rt (vc, tx, t1, b1, b8, de, fl, dbl, j, e, s, dt, ts, y) values (
		 'a''b\\c', 'line\nnext\ttab \\0 \\Z %_', 1, b'1', b'11111111', -0.001, 1e10, -0.0,
		 '{"a": "it''s \\"q\\" \\\\ b"}', 'it''s', 'x,y',
		 '2024-01-02 03:04:05.123', '2024-01-02 03:04:05', 2024)`,
		`insert into t_rt (fl, dbl, b8) values (3.4e38, 1e100, b'00000101')`,
		`insert into t_rt (dbl, fl) values (1.5e-7, -1.25)`,
		`insert into t_rt (vc) values (null)`,
	}
	r, err := c.Query(context.Background(), "select database()")
	if err != nil {
		t.Fatal(err)
	}
	yiRoundTrip(t, c, mysql.Engine{}, r.Rows[0][0].S, setup, `create table t_rt2 like t_rt`)
}

// MySQL's bytes that are no UTF-8 reach the grid as <binary n bytes>: yi
// writes no statement of them, a text blob beside them still copies (F8.7).
func TestYankInsertBinaryMySQL(t *testing.T) {
	ctx := context.Background()
	c, _, err := mysql.Connect(ctx, mysql.OwnDB(t), "", false)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	for _, q := range []string{
		`create table t_bin (id int auto_increment primary key, vbn varbinary(20))`,
		`insert into t_bin (vbn) values (x'ff'), ('abc')`,
	} {
		if _, err := c.Query(ctx, q); err != nil {
			t.Fatal(err)
		}
	}
	db0, err := c.Query(ctx, "select database()")
	if err != nil {
		t.Fatal(err)
	}
	eng, schema := mysql.Engine{}, db0.Rows[0][0].S
	cols, err := eng.TableColumns(ctx, c, schema, "t_bin")
	if err != nil {
		t.Fatal(err)
	}
	page, _, err := db.Page(ctx, c, eng, db.Query{Schema: schema, Table: "t_bin", Key: cols.Key(), Limit: 10})
	if err != nil {
		t.Fatal(err)
	}
	a := wide(160, 45)
	a.sess.Conns[0].eng = eng
	a.openTable(a.sess.Conns[0], db.Table{Schema: schema, Name: "t_bin"})
	tab := dataOf(a.focused())
	a.Update(pageMsg{tab: tab, seq: tab.seq, cols: cols, page: page})
	if text, ok := clipText(keys(t, a, "yi")); ok || a.toast != "有二进制列，复制不了" {
		t.Errorf("x'ff': copied %q, toast %q", text, a.toast)
	}
	tab.row = 1
	if text, ok := clipText(keys(t, a, "yi")); !ok || !strings.Contains(text, "'abc'") {
		t.Errorf("'abc': %q", text)
	}
}
