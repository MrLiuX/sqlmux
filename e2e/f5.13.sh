#!/usr/bin/env bash
# F5.13 INSERT 的列补全（specs/m5-workspace/task.md F5.13；tech-design §9.7「INSERT 的列」）
# 上下文识别（带 schema、引号、反引号、已写的列）由 sqlkit 的单测覆盖；这里测真实终端里的弹出、「全部列」、
# 只选一列再敲逗号、不该弹的位置，以及 generated 列不出现（PG 和 MySQL 各在自己建的库里加一张带生成列的表）。
. "$(dirname "$0")/lib.sh"
e2e_build || exit 1

pop() { e2e_panes | awk '$1 == "-" { print $2, $3, $4, $5 }' | tail -1; }
items() { local g y; g=($(pop)); [[ -n ${g[0]} ]] || return 0
  for ((y = g[1] + 1; y < g[1] + g[3] - 1; y++)); do e2e_text $((g[0] + 2)) $((g[0] + g[2] - 2)) $y | sed 's/^ *//; s/ *$//'; done; }
paste() { t set-buffer -b e2e "$1"; t paste-buffer -r -p -b e2e -t t; sleep 0.4; }
names() { items | sed 's/  .*//' | tr '\n' '|'; }
names_are() { [[ $(names) == "$1" ]] || { echo "  candidates: '$(names)', want '$1'"; false; }; }
none() { [[ -z $(pop) ]] || { echo "  popup: $(names)"; false; }; }
line() { e2e_text 104 159 $(($1 + 1)) | sed 's/ *$//'; }
cc() { echo $(( $(e2e_flag cursor_x) - 103 )); }
fresh() { key Escape; key Escape; key g g; key d G; key i; }
sel1() { [[ $(e2e_style $(( $(pop | cut -d' ' -f1) + 2 )) $(( $(pop | cut -d' ' -f2) + 1 )))  == *bg=#364a82* ]]; }   # 第一项是选中的

D=$(mktemp -d "${TMPDIR:-/tmp}/sqlmux-e2e-cfg.XXXXXX"); trap 'e2e_stop; rm -rf "$D"' EXIT
e2e_own_db || exit 1
psql "$E2E_DB" -q -v ON_ERROR_STOP=1 -c "create table t_gen (id int generated always as identity, a int, b int generated always as (a * 2) stored, d int generated by default as identity, c text)" -c "create table comment (id int, body text)" || exit 1
printf '[[connection]]\nname = "doraemon"\nengine = "postgres"\ndsn = "%s"\n' "$E2E_DB" >"$D/connections.toml"

start -C "$D"; key C-l; key i

# ---- 全部列
e2e_type "insert into t_log("; sleep 1
check "insert into t_log( ：不再敲别的就弹出，第一项是全部列（logged_at, msg），后面是两列单列，注释「全部 2 列」" eval 'names_are "logged_at, msg|logged_at|msg|" && items | head -1 | grep -q "全部 2 列"'
check "第一项选中" sel1
key Enter
check "↵：括号里是全部列，光标在 ) 前，列表关了" eval '[[ $(line 1) == "insert into t_log(logged_at, msg)" && $(cc) == 32 ]] && none'

# ---- 只选一列，敲 ", " 后少了这一列，只剩一列时不出全部列
fresh; e2e_type "insert into t_log("; sleep 1; key Down; key Enter
check "选 logged_at 单列：括号里只有它，光标在 ) 前" eval '[[ $(line 1) == "insert into t_log(logged_at)" && $(cc) == 27 ]]'
e2e_type ", "; sleep 0.8
check "敲 ', '：只剩 msg，没有「全部列」" names_are "msg|"
key Escape; key Escape

# ---- 超过 40 个字符截断，注释写总列数，接受后是完整的
fresh; e2e_type "insert into t_order("; sleep 1
check "t_order 十列：全部列那一项截断加 …，注释「全部 10 列」" eval 'it=$(items | head -1); [[ $it == "id, user_id, status, amount, paid, meta, raw…"* || $it == *"…"* ]] && [[ $it == *"全部 10 列"* ]] || { echo "  $it"; false; }'
key Enter
check "接受：行尾是 …created_at, deleted_at)，光标在 ) 前" eval '[[ $(line 1) == *", created_at, deleted_at)" ]]'
key Escape; key 0; sleep 0.3
check "回到行首：insert into t_order(id, user_id, status, amount,（窗口只放得下前面一截）" eval '[[ $(line 1) == "insert into t_order(id, user_id, status, amount,"* && $(line 1) != *"…"* ]] || { echo "  $(line 1)"; false; }'

# ---- 前缀、已经写了的列（光标前后都算）
fresh; e2e_type "insert into t_sku(c"; sleep 0.8
check "有前缀：没有全部列，只列匹配的（code），不含不匹配的" eval 'names | grep -q "^code|" && ! names | grep -q "全部" && ! items | grep -q "，\|, "'
fresh; e2e_type "insert into t_sku(code, "; sleep 0.8
check "code 已经写了：剩下 barcode、title、price，第一项是全部列（三列）" names_are "barcode, title, price|barcode|title|price|"
fresh; paste "insert into t_sku(, title)"; key Escape; key 0; key f "("; key a; e2e_type t; sleep 0.8
check "title 写在光标后面也算已经写了：前缀 t 没有候选" none
key BSpace; e2e_type c; sleep 0.8
check "前缀 c：只有 code（barcode 不是词首，title 已写）" names_are "code|"
key Escape; key Escape

# ---- schema、引号
fresh; e2e_type "insert into public.t_log("; sleep 1
check "带 schema：public.t_log( 弹出" names_are "logged_at, msg|logged_at|msg|"
fresh; e2e_type 'insert into "t_log" ('; sleep 1
check "带引号、括号前有空格：弹出" names_are "logged_at, msg|logged_at|msg|"
fresh; e2e_type "insert into t_log (logged_at, "; sleep 0.8
check "逗号之后：只剩 msg" names_are "msg|"

# ---- 不该弹的位置
fresh; e2e_type "insert into t_log values ("; sleep 0.8
check "values ( 之后不弹" none
fresh; e2e_type "insert into nosuch("; sleep 0.8
check "catalog 里没有的表不弹" none
fresh; e2e_type "insert into t_log select ("; sleep 0.8
check "insert … select ( 不弹" none
fresh; e2e_type "select * from t_log where ("; sleep 0.8
check "普通语句里的括号不弹" none
fresh; e2e_type "insert into t_log(logged_at) values (1) , ("; sleep 0.8
check "values 列表后的括号不弹（只认 insert into 表 后面的第一个括号）" none

# ---- generated always 的列不出现（PG：identity always、stored 生成列；by default 的 identity 可以写）
fresh; e2e_type "insert into t_gen("; sleep 1
check "PG：t_gen 里 id（identity always）和 b（生成列）不出现，d（by default）出现" names_are "a, d, c|a|d|c|"
fresh; e2e_type "insert into comment("; sleep 1
check "名字是关键字的表（PG 的 comment）也弹列表" names_are "id, body|id|body|"
fresh; e2e_type "insert into public.comment ("; sleep 1
check "带 schema 的 public.comment 也弹" names_are "id, body|id|body|"
key Escape; key Escape
e2e_stop

# ---- MySQL：database 里的表，反引号；auto_increment 可以写，生成列（STORED / VIRTUAL）不行，DEFAULT_GENERATED 不算
e2e_own_mydb || exit 1
e2e_mysql "sqlmux_e2e_$$" <<<"create table t_gen (id int auto_increment primary key, a int, b int as (a * 2) stored, v int as (a + 1) virtual, e int default (1), c text); create table \`key\` (id int, v text)" || exit 1
printf '[[connection]]\nname = "my"\nengine = "mysql"\ndsn = "%s"\n' "$E2E_MYDB" >"$D/connections.toml"
start -C "$D"; key C-l; key i
e2e_type "insert into t_log("; sleep 1.2
check "MySQL：t_log( 弹出全部列" eval 'names | grep -q "^logged_at, msg|logged_at|msg|$" || { echo "  $(names)"; false; }'
fresh; e2e_type 'insert into `t_log` ('; sleep 1
check "MySQL：反引号的表名" eval 'names | grep -q "^logged_at, msg|"'
fresh; e2e_type "insert into t_gen("; sleep 1
check "MySQL：id、a、e、c 出现；b（STORED GENERATED）、v（VIRTUAL GENERATED）不出现" names_are "id, a, e, c|id|a|e|c|"
fresh; e2e_type 'insert into `key`('; sleep 1
check "MySQL：名字是关键字的表 key（反引号）也弹列表" names_are "id, v|id|v|"
fresh; e2e_type "insert into key("; sleep 1
check "MySQL：不加反引号的 key( 也弹" names_are "id, v|id|v|"
fresh; e2e_type "replace into t_log("; sleep 1
check "MySQL：replace into 也弹" eval 'names | grep -q "^logged_at, msg|"'
key Escape; key Escape

e2e_done
